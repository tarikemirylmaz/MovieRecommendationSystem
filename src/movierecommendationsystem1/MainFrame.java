    // Loads user, movie and recommendation data into the GUI
    private void loadData(){
        try{
            // Reads all users from CSV files
            mainUsers = DataLoader.loadUsers("data/main_data.csv");
            targetUsers = DataLoader.loadUsers("data/target_user.csv");
            // Loads movie titles and movie ids
            movieTitles = DataLoader.loadMovies("data/movies.csv");
            movieIds = DataLoader.getMovieIds("data/movies.csv");
            
            engine = new RecommendationEngine(mainUsers, movieTitles, movieIds);
            
            // Adds target users into combo box
            for(int i = 0; i < targetUsers.size(); i++){
                userComboBox.addItem("User " + targetUsers.get(i).userId);
            }

            // random movie list
            randomMovieIds = new ArrayList<>(movieIds);

               Collections.shuffle(randomMovieIds);

            randomMovieIds = randomMovieIds.subList(0, Math.min(10, randomMovieIds.size()));

            JComboBox<String>[] combos = new JComboBox[]{movieCombo1,movieCombo2,movieCombo3,movieCombo4,movieCombo5};
            // Fills combo boxes with movie titles
            for(int i = 0; i < combos.length; i++){
                for(int j = 0; j < randomMovieIds.size(); j++){
                    String title = movieTitles.getOrDefault(randomMovieIds.get(j),"Movie " + randomMovieIds.get(j));
                    combos[i].addItem(title );
                }
                combos[i].setSelectedIndex(i % randomMovieIds.size());
        }

        }catch(Exception e){
            JOptionPane.showMessageDialog(this,"Data loading error: " + e.getMessage());
        }
    }

