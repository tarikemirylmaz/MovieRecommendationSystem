    // Generates movie recommendations according to selected target user
    private void btnGetRec1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGetRec1ActionPerformed
        
        int selectedIndex = userComboBox.getSelectedIndex();
        int X, K;

        try{
            // Reads X and K values from text fields
            X = Integer.parseInt(xField1.getText());
            K = Integer.parseInt(kField1.getText());

        }catch(NumberFormatException ex){
            resultArea1.setText("X and K must be integers!");
            return;
        }

        UserEntry target = targetUsers.get(selectedIndex);
        List<String> recs = engine.getRecommendations(target.ratings,X,K);
        StringBuilder sb = new StringBuilder();
        sb.append("Recommendations:\n\n");
        // Adds recommended movies into result text
        for(int i = 0; i < recs.size(); i++){
            sb.append(i + 1).append(". ").append(recs.get(i)).append("\n");
        }
        // Shows message if no recommendation exists
        if(recs.isEmpty()){
            sb.append("No recommendations found.");
        }
        // Displays recommendations on GUI
        resultArea1.setText(sb.toString());
    }//GEN-LAST:event_btnGetRec1ActionPerformed
    // Generates recommendations according to selected movies and ratings
    private void btnGetRec2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGetRec2ActionPerformed
        int X, K;

        try{
            // Reads X and K values from text fields
            X = Integer.parseInt(xField2.getText());
            K = Integer.parseInt(kField2.getText());
            
        }catch(NumberFormatException ex){
           resultArea2.setText("X and K must be integers!");
            return;
        }
        // Creates user rating vector
        double[] userVector = new double[movieIds.size()];
        // Stores selected movie ids to prevent duplicates
        Set<Integer> used = new HashSet<>();

        JComboBox<String>[] combos = new JComboBox[]{movieCombo1,movieCombo2,movieCombo3,movieCombo4,movieCombo5};
        JTextField[] ratingFs = new JTextField[]{ratingField1,ratingField2,ratingField3,ratingField4,ratingField5};
        // Reads selected movies and ratings
        for(int i = 0; i < 5; i++){
            int mid = randomMovieIds.get(combos[i].getSelectedIndex());
            // Checks whether the same movie is selected twice
            if(used.contains(mid)){
                resultArea2.setText("Please select 5 different movies!");
                return;
            }

            used.add(mid);
            int rating;

            try{
                // Reads rating value
                rating = Integer.parseInt(ratingFs[i].getText());

            }catch(NumberFormatException ex){
                resultArea2.setText("Rating must be an integer!");
                return;
            }
            // Checks rating range
            if(rating < 1 || rating > 5){
                resultArea2.setText("Rating must be between 1 and 5!");
                return;
            }
            // Places rating into correct movie index
            int idx = movieIds.indexOf(mid);
            if(idx >= 0){
                userVector[idx] = rating;
            }
        }
        // Gets recommendations from recommendation engine
        List<String> recs = engine.getRecommendations(userVector,X,K);
        StringBuilder sb = new StringBuilder();
        sb.append("Recommendations:\n\n");
        // Adds recommended movies into result text
        for(int i = 0; i < recs.size(); i++){
            sb.append(i + 1).append(". ").append(recs.get(i)).append("\n");
        }
        // Shows message if no recommendation exists
        if(recs.isEmpty()){
            sb.append("No recommendations found.");
        }
        // Displays recommendations on GUI
        resultArea2.setText(sb.toString());
    }//GEN-LAST:event_btnGetRec2ActionPerformed

